// Writes src/environments/firebase.config.ts from environment variables.
// In CI they come from the GitHub repository secrets; locally from frontend/.env (see .env.example).
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = join(root, '.env');
if (existsSync(envFile)) {
  process.loadEnvFile(envFile);
}

const missing = [];
const read = (name) => {
  const value = process.env[name]?.trim();
  if (!value) missing.push(name);
  return value ?? '';
};

const firebaseOptions = (prefix) => ({
  apiKey: read(`${prefix}FIREBASE_API_KEY`),
  authDomain: read(`${prefix}FIREBASE_AUTH_DOMAIN`),
  projectId: read(`${prefix}FIREBASE_PROJECT_ID`),
  storageBucket: read(`${prefix}FIREBASE_STORAGE_BUCKET`),
  messagingSenderId: read(`${prefix}FIREBASE_MESSAGING_SENDER_ID`),
  appId: read(`${prefix}FIREBASE_APP_ID`),
});

const firebase = firebaseOptions('');
const aiFirebase = firebaseOptions('AI_');
const aiRecaptchaSiteKey = read('AI_RECAPTCHA_SITE_KEY');

if (missing.length) {
  console.error(`Missing environment variables:\n  ${missing.join('\n  ')}`);
  console.error('Set them in frontend/.env (copy .env.example) or as GitHub repository secrets.');
  process.exit(1);
}

const json = (value) => JSON.stringify(value, null, 2);
const output = `// Generated by scripts/write-firebase-config.mjs. Do not edit or commit.
import { FirebaseOptions } from 'firebase/app';

export const firebase: FirebaseOptions = ${json(firebase)};

export const aiFirebase: FirebaseOptions = ${json(aiFirebase)};

export const aiRecaptchaSiteKey = ${json(aiRecaptchaSiteKey)};
`;

writeFileSync(join(root, 'src/environments/firebase.config.ts'), output);
console.log('Wrote src/environments/firebase.config.ts');
